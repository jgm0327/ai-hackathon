/**
 * 이 직군에서 자주 묻는 역량 중, 유저가 **아직 한 건도 기록하지 않은** 것들.
 *
 * 비교는 이름이 정확히 같은지로만 한다 — 비슷한 이름을 같은 역량으로 치려면
 * 임베딩이 필요한데(CLAUDE.md 2.3), 이건 안내 문구일 뿐이라 그만한 비용을 들일
 * 이유가 없다. 틀려도 손해는 "이미 있는 역량을 또 권한다" 정도다.
 *
 * 직군을 모르면(온보딩 스킵) 빈 배열 — 아무 직군의 목록도 임의로 고르지 않는다.
 */
export function missingCoreCompetencies(
  jobField: string | null | undefined,
  ownedTags: string[],
): string[] {
  if (!jobField) return [];
  const core = CORE_COMPETENCIES[jobField];
  if (!core) return [];
  const owned = new Set(ownedTags);
  return core.filter((name) => !owned.has(name));
}
